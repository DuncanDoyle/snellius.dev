// Copies the finding reference from the Snellius repo into the docs. Run: npm run sync:findings [ref]
import { writeFile } from "node:fs/promises";

const ref = process.argv[2] ?? "main";
const repo = "https://github.com/DuncanDoyle/snellius";
const res = await fetch(`https://raw.githubusercontent.com/DuncanDoyle/snellius/${ref}/docs/findings.md`);
if (!res.ok) throw new Error(`fetch findings.md at ${ref}: ${res.status}`);

const body = (await res.text())
  .replace(/^# .*\n+/, "") // Starlight renders the title from frontmatter
  .replace(/\]\(\.\.\/([^)]+)\)/g, (_, path) => {
    const [file, anchor] = path.split("#");
    return file === "README.md" ? `](${repo}${anchor ? `#${anchor}` : ""})` : `](${repo}/blob/main/${path})`;
  });

const page = `---
title: Finding codes
description: Every finding Snellius raises, its cause, its evidence and how to fix it.
---

<!-- Generated by scripts/sync-findings.mjs from ${repo}/blob/${ref}/docs/findings.md. Edit it there. -->

${body}`;
await writeFile(new URL("../src/content/docs/docs/findings.md", import.meta.url), page);
console.log(`findings.md synced from ${ref}`);
